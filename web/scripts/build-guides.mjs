import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { readChrome } from "./sync-chrome.mjs";
import { collections, established } from "../content/guides.mjs";

const root = new URL("../", import.meta.url);
const output = new URL("guides/", root);
const origin = "https://www.fud-ai.app";
const marker = "<!-- Generated by scripts/build-guides.mjs. Edit web/content/ instead. -->";
const escapeHtml = (value) => value.replace(/[&<>"']/g, (char) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[char]);
const json = (value) => JSON.stringify(value).replaceAll("<", "\\u003c");
const checkedHref = (href) => {
  if (!/^\/(?!\/)[a-z\d/#-]*$|^https:\/\/[^/\s]+(?:\/[^\s]*)?$/i.test(href)) {
    throw new Error(`Unsupported guide link: ${href}`);
  }
  return escapeHtml(href);
};
const link = ([label, href]) => `<a href="${checkedHref(href)}">${escapeHtml(label)}</a>`;
const links = (items) => `<ul>${items.map((entry) => `<li>${link(entry)}</li>`).join("\n")}</ul>`;
const publication = "2026-11-26";

const [style, header, footer] = await readChrome();
const social = (await readFile(new URL("index.html", root), "utf8"))
  .match(/<meta name="twitter:site" content="(@[a-z0-9_]+)">/i)?.[1];
const bySlug = new Map();
const unique = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
for (const group of collections) {
  if (!unique.test(group.id) || !group.guides.length) throw new Error(`Invalid collection: ${group.id}`);
  for (const [slug, title, summary, sections, refs = [], related = [], updated = publication] of group.guides) {
    const content = sections.flat().flat().join(" ");
    if (!unique.test(slug) || bySlug.has(slug) || !title || !summary || sections.length < 2 || content.split(/\s+/).length < 65) {
      throw new Error(`Missing, duplicate, or thin guide: ${slug}`);
    }
    if (group.id === "comparisons" && !refs.some(([, href]) => href.startsWith("https://") && !href.includes("fud-ai"))) {
      throw new Error(`Comparison without a third-party source: ${slug}`);
    }
    bySlug.set(slug, { title, summary, sections, refs, related, group, updated });
  }
}

function page({ title, description, path, updated, crumbs, body, article }) {
  const url = `${origin}${path}`;
  const fullTitle = `${title} | Fud AI`;
  const image = `${origin}/assets/opengraph.jpg?v=20261020`;
  const imageAlt = "Fud AI: Just say what you ate. A chicken burrito bowl logged at 620 kcal beside the app's glowing pink voice orb.";
  const graph = [{
    "@type": "WebPage", "@id": `${url}#webpage`, url, name: fullTitle, description,
    inLanguage: "en", dateModified: updated, isPartOf: { "@id": `${origin}/#website` },
    breadcrumb: { "@id": `${url}#breadcrumb` },
  }, {
    "@type": "BreadcrumbList", "@id": `${url}#breadcrumb`,
    itemListElement: crumbs.map(([name, href], i) =>
      ({ "@type": "ListItem", position: i + 1, name, item: origin + href })),
  }];
  if (article) graph.push({
    "@type": "Article", "@id": `${url}#article`, headline: title, description,
    datePublished: publication, dateModified: updated, mainEntityOfPage: { "@id": `${url}#webpage` },
    author: { "@type": "Organization", name: "Fud AI", url: `${origin}/` },
  });
  return `<!doctype html>
${marker}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${escapeHtml(fullTitle)}</title>
  <meta name="description" content="${escapeHtml(description)}">
  <meta name="robots" content="index,follow,max-image-preview:large">
  <link rel="canonical" href="${url}">
  <link rel="icon" href="/assets/fud-app-icon-180.png">
  <link rel="apple-touch-icon" href="/assets/fud-app-icon-180.png">
  ${style}
  <meta name="theme-color" content="#fffdfc" media="(prefers-color-scheme: light)">
  <meta name="theme-color" content="#121214" media="(prefers-color-scheme: dark)">
  <meta property="og:type" content="${article ? "article" : "website"}">
  <meta property="og:site_name" content="Fud AI">
  <meta property="og:title" content="${escapeHtml(fullTitle)}">
  <meta property="og:description" content="${escapeHtml(description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${image}">
  <meta property="og:image:type" content="image/jpeg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${escapeHtml(imageAlt)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="${image}">
  <meta name="twitter:image:alt" content="${escapeHtml(imageAlt)}">
  ${social ? `<meta name="twitter:site" content="${social}">` : ""}
  <script type="application/ld+json">${json({ "@context": "https://schema.org", "@graph": graph })}</script>
</head>
<body>
  <a class="skip" href="#main">Skip to content</a>
${header}
  <main id="main" class="doc">
    <div class="shell">
      <article class="legal-content">
        <nav class="legal-jumps" aria-label="Breadcrumbs">${crumbs.slice(0, -1).map(link).join(" ")}</nav>
        <h1>${escapeHtml(title)}</h1>
        <p class="lede">${escapeHtml(description)}</p>
${body}
      </article>
    </div>
  </main>
${footer}
</body>
</html>
`;
}

function section([title, ...blocks]) {
  return `<h2>${escapeHtml(title)}</h2>\n${blocks.map((block) => Array.isArray(block)
    ? `<ol>${block.map((step) => `<li>${escapeHtml(step)}</li>`).join("\n")}</ol>`
    : `<p>${escapeHtml(block)}</p>`).join("\n")}`;
}

async function writeOwned(file, html) {
  const current = await readFile(file, "utf8").catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return "";
  });
  if (current && !current.includes(marker)) throw new Error(`Won't overwrite hand-edited HTML: ${file.pathname}`);
  if (current !== html) await writeFile(file, html);
}

await mkdir(output, { recursive: true });
for (const [slug, guide] of bySlug) {
  const { title, summary, sections, refs, related, group, updated } = guide;
  const choices = related.length ? related : group.guides.map(([key]) => key).filter((key) => key !== slug).slice(0, 3);
  const recommendations = choices.map((key) => {
    if (established[key]) return established[key];
    if (!bySlug.has(key) || key === slug) throw new Error(`${slug}: invalid related guide ${key}`);
    return [bySlug.get(key).title, `/guides/${key}`];
  });
  const path = `/guides/${slug}`;
  await writeOwned(new URL(`${slug}.html`, output), page({
    title, description: summary, path, updated, article: true,
    crumbs: [["Home", "/"], ["Guides", "/guides"], [title, path]],
    body: [
      ...sections.map(section),
      ...(refs.length ? ["<h2>Sources and further reading</h2>", links(refs)] : []),
      "<h2>Related guides</h2>", links([...recommendations, [`All ${group.title.toLowerCase()} guides`, `/guides#${group.id}`]]),
    ].join("\n"),
  }));
}
for (const name of await readdir(output)) {
  if (name.endsWith(".html") && !bySlug.has(name.slice(0, -5))) {
    const file = new URL(name, output);
    if (!(await readFile(file, "utf8")).includes(marker)) throw new Error(`Unknown file in generated guides directory: ${name}`);
    await unlink(file);
  }
}

await writeOwned(new URL("guides.html", root), page({
  title: "Guides and comparisons", path: "/guides",
  description: "Learn how to log meals, set up AI, track nutrition, sync health data, and choose a calorie tracker that fits how you work.",
  updated: [...bySlug.values()].map(({ updated }) => updated).sort().at(-1),
  crumbs: [["Home", "/"], ["Guides", "/guides"]],
  body: [
    `<nav class="legal-jumps" aria-label="Guide topics">${collections.map(({ title, id }) => link([title, `/guides#${id}`])).join(" ")}</nav>`,
    ...collections.map(({ id, title, intro, guides }) =>
      `<h2 id="${id}">${escapeHtml(title)}</h2>\n<p>${escapeHtml(intro)}</p>\n<ul>${guides.map(([slug, label, detail]) =>
        `<li>${link([label, `/guides/${slug}`])} — ${escapeHtml(detail)}</li>`).join("\n")}</ul>`),
    "<h2>Product overview and alternatives</h2>", links(Object.values(established)),
  ].join("\n"),
}));
console.log(`Built ${bySlug.size} guides and the guides hub.`);
